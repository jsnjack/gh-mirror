package commentpolicy

import "testing"

func TestDetectedAI(t *testing.T) {
	for _, tc := range []struct{ name, body, want string }{
		{"human posted Claude reply", "Fixed the upload failure.\n\n_🤖 Addressed by [Claude Code](https://claude.com/claude-code)_\n", "claude"},
		{"legacy generated footer", "Review findings.\n\n🤖 Generated with [Claude Code](https://claude.ai/code)", "claude"},
		{"plain attribution", "Review findings.\n\n*Generated by Claude Code*", "claude"},
		{"hidden marker", "Review findings.\n<!-- gh-mirror:ai-generated:claude -->", "claude"},
		{"ordinary mention", "Claude Code helped me debug this, but I verified the fix manually.", ""},
		{"quoted footer", "Example:\n> 🤖 Generated with [Claude Code](https://claude.ai/code)", ""},
		{"fenced example", "Example:\n```md\nGenerated by Claude Code\n```", ""},
		{"unclosed fenced example", "Example:\n~~~md\nGenerated by Claude Code", ""},
		{"indented example", "Example:\n    Generated by Claude Code", ""},
		{"inline code example", "`Generated by Claude Code`", ""},
		{"footer after longer fence", "````md\n```\nexample\n````\n\nGenerated by Claude Code", "claude"},
		{"inline triple backticks before marker", "```npm ci``` fails here.\n<!-- gh-mirror:ai-generated:claude -->", "claude"},
		{"inline triple backticks before footer", "```make check``` passes.\n\n🤖 Generated with [Claude Code](https://claude.ai/code)", "claude"},
		{"footer is not final", "Generated by Claude Code\nThat is an example, not this comment's attribution.", ""},
		{"wrong link", "Generated with [Claude Code](https://example.com)", ""},
		{"empty", "", ""},
	} {
		t.Run(tc.name, func(t *testing.T) {
			c := Comment{Author: Author{Login: "alice", Type: "User"}, Body: tc.body}
			if got := DetectedAI(c); got != tc.want {
				t.Fatal(got, tc.want)
			}
		})
	}
}

func TestDeclaredAISelection(t *testing.T) {
	for _, name := range []string{"individual comments", "excluded root", "explicit include", "filter disabled"} {
		t.Run(name, func(t *testing.T) {
			p := Policy{ExcludeKnownAI: true, ExcludeAIThreads: true}
			comments := []Comment{
				{ID: "review:1", Repo: "o/r", Number: 1, Author: Author{Login: "alice", Type: "User"}, Body: "Human review."},
				{ID: "review:2", Repo: "o/r", Number: 1, Parent: "review:1", Author: Author{Login: "alice", Type: "User"}, Body: "Fixed.\n\n_🤖 Addressed by [Claude Code](https://claude.com/claude-code)_"},
				{ID: "review:3", Repo: "o/r", Number: 1, Parent: "review:2", Author: Author{Login: "alice", Type: "User"}, Body: "Human follow-up."},
			}
			switch name {
			case "excluded root":
				comments[1].Parent = ""
			case "explicit include":
				p.IncludeAuthors = []string{"alice"}
			case "filter disabled":
				p.ExcludeKnownAI = false
			}
			out, err := Select(comments, map[string]Policy{"o/r": p})
			if err != nil {
				t.Fatal(err)
			}
			if name == "explicit include" || name == "filter disabled" {
				if len(out) != 0 {
					t.Fatal(out)
				}
				return
			}
			if out["review:2"].Provider != "claude" || out["review:1"].Reason != "" {
				t.Fatal(out)
			}
			if name == "excluded root" {
				if out["review:3"].Root != "review:2" {
					t.Fatal(out)
				}
			} else if out["review:3"].Reason != "" {
				t.Fatal("human-started discussion lost", out)
			}
		})
	}
}
