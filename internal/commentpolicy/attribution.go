package commentpolicy

import (
	"strings"
)

// DetectedAI recognizes a known account or an explicit final-line attribution.
func DetectedAI(c Comment) string {
	if provider := KnownAI(c.Author); provider != "" {
		return provider
	}
	var footer string
	var delimiter byte
	var length int
	for _, line := range strings.Split(c.Body, "\n") {
		trimmed := strings.TrimSpace(line)
		if trimmed == "" {
			continue
		}
		footer = ""
		indented := strings.HasPrefix(line, "\t") || strings.HasPrefix(line, "    ")
		if !indented && (strings.HasPrefix(trimmed, "```") || strings.HasPrefix(trimmed, "~~~")) {
			ch := trimmed[0]
			count := len(trimmed) - len(strings.TrimLeft(trimmed, string(ch)))
			if delimiter == 0 {
				delimiter, length = ch, count
			} else if delimiter == ch && count >= length && strings.TrimSpace(trimmed[count:]) == "" {
				delimiter, length = 0, 0
			}
			continue
		}
		if delimiter == 0 && !indented {
			footer = trimmed
		}
	}
	if footer == "<!-- gh-mirror:ai-generated:claude -->" {
		return "claude"
	}
	footer = strings.TrimSpace(strings.Trim(footer, "*_"))
	footer = strings.TrimSpace(strings.TrimPrefix(footer, "🤖"))
	footer = strings.ToLower(footer)
	for _, prefix := range []string{"addressed by ", "generated with ", "generated by ", "reviewed by ", "reviewed with ", "implemented by ", "fixed by "} {
		if !strings.HasPrefix(footer, prefix) {
			continue
		}
		name := strings.TrimPrefix(footer, prefix)
		if name == "claude code" || name == "[claude code](https://claude.ai/code)" || name == "[claude code](https://claude.com/claude-code)" {
			return "claude"
		}
	}
	return ""
}
